ESPN_SAMPLE = {
    "events": [
        {
            "name": "Cleveland Browns at Pittsburgh Steelers",
            "status": {"type": {"state": "in", "shortDetail": "2nd 9:40"}},
            "competitions": [
                {
                    "competitors": [
                        {"homeAway": "home", "score": "7", "team": {"abbreviation": "PIT"}},
                        {"homeAway": "away", "score": "3", "team": {"abbreviation": "CLE"}},
                    ]
                }
            ],
        }
    ]
}


def test_parse_espn_and_feed():
    gs = parse_espn(ESPN_SAMPLE, "PIT")
    assert (gs.team_score, gs.opponent, gs.opp_score, gs.status) == (7, "CLE", 3, "in")
    assert parse_espn({"events": []}, "PIT").status == "none"
    feed = EspnFeed("PIT", fetch=lambda url: json.dumps(ESPN_SAMPLE).encode())
    assert feed.poll().team_score == 7


def test_watcher_and_bridge():
    w = ScoreWatcher()
    assert w.update(GameState("PIT", 0, "CLE", 0, "pre")) == []
    assert w.update(GameState("PIT", 6, "CLE", 0, "in")) == ["SCORE 6 6"]
    assert w.update(GameState("PIT", 6, "CLE", 7, "in")) == []  # opponent scoring is ignored
    sent = run_bridge(demo_game(), lambda c: None, polls=20, interval_s=0, sleep=lambda s: None, log=lambda s: None)
    assert sent == ["SCORE 6 6", "SCORE 1 7", "SCORE 3 10", "SCORE 7 17"]
    assert MockFeed([GameState("PIT", 1, "X", 0, "in")]).poll().team_score == 1


def test_real_bench_commands_and_parsers():
    assert mpremote_flash_cmd("/dev/ttyACM0", "/tmp/main.py") == [
        "mpremote",
        "connect",
        "/dev/ttyACM0",
        "fs",
        "cp",
        "/tmp/main.py",
        ":main.py",
        "+",
        "reset",
    ]
    cmd = mpremote_ina_cmd("COM3")
    assert cmd[:4] == ["mpremote", "connect", "COM3", "exec"] and "readfrom_mem(64,1,2)" in cmd[4]
    compile(cmd[4], "snippet", "exec")
    assert sigrok_cmd(["D0", "D1"], 2.0) == [
        "sigrok-cli",
        "-d",
        "fx2lafw",
        "--config",
        "samplerate=1m",
        "--channels",
        "D0,D1",
        "--time",
        "2000ms",
        "-O",
        "csv",
    ]
    csv_text = "; CSV, generated by sigrok\nD0,D1\n" + "\n".join(f"{(i // 10) % 2},{1}" for i in range(400))
    tr = parse_sigrok_csv(csv_text, ["D0", "D1"])
    assert tr["D0"].edges == 39 and tr["D1"].edges == 0 and tr["D1"].high_fraction == 1.0
    assert tr["D0"].pwm_hz == pytest.approx(50000, rel=0.01)  # period 20 samples at 1 MHz


def test_real_bench_read_current_with_fake_runner():
    calls = []

    def runner(cmd, timeout):
        calls.append(cmd)
        if "exec" in cmd:
            return '{"shunt_mv": 1.5, "bus_v": 3.28}\n'
        return ""

    rb = RealBench(port="/dev/ttyACM0", runner=runner, use_helper=False)
    r = rb.read_current()
    assert r.avg_ma == pytest.approx(15.0) and r.bus_v == 3.28
    assert calls[-1][-1] == "reset"  # main.py restarted afterwards
    rb2 = RealBench(port="/dev/ttyACM0", runner=runner, uhubctl=["-l", "1-1", "-p", "2"])
    assert "switched off" in rb2.power_cut("test")
    assert calls[-1] == ["uhubctl", "-l", "1-1", "-p", "2", "-a", "off"]


def test_mcp_server_tools():
    pytest.importorskip("mcp")
    from hands.bench.mcp_server import TOOL_NAMES, build_server, sim_bench_for
    from hands.gadgets.steelers import FIRMWARE

    bench = sim_bench_for("steelers")
    srv = build_server(bench, bench.design)
    no_design = build_server(sim_bench_for("steelers"))

    async def go():
        names = [t.name for t in await srv.list_tools()]
        assert sorted(names) == sorted(TOOL_NAMES)
        r = await no_design.call_tool("flash_firmware", {"code": FIRMWARE})
        assert "refusing to flash" in str(r)
        r = await srv.call_tool("flash_firmware", {"code": FIRMWARE.replace("Pin(15, Pin.OUT)", "Pin(26, Pin.OUT)")})
        assert "rejected by the linter" in str(r)
        r = await srv.call_tool(
            "check_design",
            {
                "design_json": json.dumps(
                    {
                        "parts": {"led1": "led_red"},
                        "nets": {"A": ["pico.GP2", "led1.anode"], "GND": ["led1.cathode"]},
                        "pin_map": {"L": "GP2"},
                    }
                )
            },
        )
        assert "led_resistor" in str(r)
        r = await srv.call_tool("check_design", {"design_json": "nope"})
        assert "structure" in str(r)
        r = await srv.call_tool("flash_firmware", {"code": FIRMWARE})
        assert "READY" in str(r)
        await srv.call_tool("write_serial", {"line": "SCORE 7 7"})
        r = await srv.call_tool("read_current", {"seconds": 1.0})
        assert "max_ma" in str(r)
        r = await srv.call_tool("power_cut", {"reason": "test"})
        assert "UNPLUG" in str(r)
        r = await srv.call_tool("read_serial", {"seconds": 0.1})
        assert "error" in str(r)  # board unpowered after power_cut

    asyncio.run(go())


def test_web_ui(inv, steelers_design):
    from hands.webui.server import make_server

    guide = build_guide(place(steelers_design, inv), inv)
    srv = make_server(guide, port=0, photo_check=lambda: [])  # noqa: PIE807 - legacy zero-arg callback
    port = srv.server_address[1]
    t = threading.Thread(target=srv.serve_forever, daemon=True)
    t.start()
    try:
        base = f"http://127.0.0.1:{port}"
        html = urllib.request.urlopen(base + "/").read().decode()
        assert "Hands" in html
        steps = json.loads(urllib.request.urlopen(base + "/api/steps").read())
        assert len(steps["steps"]) == len(guide.steps) and steps["camera"] is True
        svg = urllib.request.urlopen(base + "/api/steps/3/svg").read().decode()
        assert svg.startswith("<svg")
        req = urllib.request.Request(base + "/api/steps/3/done", method="POST")
        assert json.loads(urllib.request.urlopen(req).read())["ok"]
        assert guide.steps[3].done
        req = urllib.request.Request(base + "/api/photo_check", method="POST")
        assert json.loads(urllib.request.urlopen(req).read())["ok"] is True
    finally:
        srv.shutdown()


def test_metrics_report(tmp_path):
    p = tmp_path / "m.jsonl"
    m = Metrics(p, gadget="g", mode="sim")
    m.event("run_start")
    m.event(
        "run_end",
        success=True,
        metrics={
            "time_to_working_s": 600,
            "debug_rounds": 2,
            "design_errors_caught": 1,
            "errors_caught_pre_power": 1,
            "errors_caught_post_power": 1,
            "llm_calls": 4,
        },
    )
    rep = summary_report(p)
    assert "WORKING" in rep and "10.0 min" in rep
    assert "No runs" in summary_report(tmp_path / "missing.jsonl")


